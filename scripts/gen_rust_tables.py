#!/usr/bin/env python3
"""
Automated Python codegen pipeline for SiliconMC Rust port.
Extracts exact Minecraft 26.3 runtime tables directly from Java OracleMain + built-in reports + datapack JSONs,
and emits deterministic, compiler-checked Rust source files under rust/crates/mc-data/src/generated/.
"""

import json
import math
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORTS_DIR = REPO_ROOT / "generated" / "reports"
DATA_MC_DIR = REPO_ROOT / "src" / "main" / "resources" / "data" / "minecraft"
RUST_GEN_DIR = REPO_ROOT / "rust" / "crates" / "mc-data" / "src" / "generated"


def call_oracle(requests: list[dict]) -> list[dict]:
    cp_sep = ";" if sys.platform == "win32" else ":"
    cp = f"{REPO_ROOT / 'target' / 'classes'}{cp_sep}{REPO_ROOT / 'target' / 'siliconmc-26.3-SNAPSHOT-shaded.jar'}"
    payload = "\n".join(json.dumps(r) for r in requests + [{"op": "quit"}]) + "\n"
    proc = subprocess.run(
        ["java", "-Xmx1G", "-cp", cp, "com.siliconmc.oracle.OracleMain"],
        input=payload,
        text=True,
        capture_output=True,
        cwd=REPO_ROOT,
        check=True,
    )
    lines = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
    results = [json.loads(line) for line in lines]
    for r in results:
        if not r.get("ok"):
            raise RuntimeError(f"Oracle error: {r}")
    return results[:-1]


def fmt_f32(val: float) -> str:
    if math.isnan(val):
        return "f32::NAN"
    if math.isinf(val):
        return "f32::INFINITY" if val > 0 else "f32::NEG_INFINITY"
    s = repr(float(val))
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return f"{s}_f32"


def fmt_f64(val: float) -> str:
    s = repr(float(val))
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return f"{s}_f64"


def gen_block_props(runtime_tables: dict) -> None:
    states = runtime_tables["block_states"]
    blocks_json = json.loads((REPORTS_DIR / "blocks.json").read_text(encoding="utf-8"))
    state_prop_strings: list[str] = [""] * len(states)
    for _block_name, bdata in blocks_json.items():
        for st in bdata["states"]:
            sid = int(st["id"])
            props = st.get("properties")
            if props and sid < len(state_prop_strings):
                parts = [f"{k}={v}" for k, v in sorted(props.items())]
                state_prop_strings[sid] = ",".join(parts)

    out = RUST_GEN_DIR / "block_props.rs"
    lines = [
        "// @generated by scripts/gen_rust_tables.py from live Minecraft 26.3 Block.BLOCK_STATE_REGISTRY.",
        "// Do not edit manually.",
        "",
        "pub const FLAG_IS_AIR: u16 = 1 << 0;",
        "pub const FLAG_PROPAGATES_SKYLIGHT_DOWN: u16 = 1 << 1;",
        "pub const FLAG_CAN_OCCLUDE: u16 = 1 << 2;",
        "pub const FLAG_IS_SOLID: u16 = 1 << 3;",
        "pub const FLAG_CAN_BE_REPLACED: u16 = 1 << 4;",
        "pub const FLAG_HAS_FLUID: u16 = 1 << 5;",
        "pub const FLAG_IS_FLUID_SOURCE: u16 = 1 << 6;",
        "pub const FLAG_USE_SHAPE_FOR_LIGHT_OCCLUSION: u16 = 1 << 7;",
        "pub const FLAG_REQUIRES_CORRECT_TOOL: u16 = 1 << 8;",
        "pub const FLAG_MOTION_BLOCKING: u16 = 1 << 9;",
        "pub const FLAG_MOTION_BLOCKING_NO_LEAVES: u16 = 1 << 10;",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct BlockStateProps {",
        "    pub light_emission: u8,",
        "    pub light_dampening: u8,",
        "    pub flags: u16,",
        "    pub item_id: u16,",
        "    pub destroy_speed: f32,",
        "}",
        "",
        "impl BlockStateProps {",
        "    #[inline] pub const fn is_air(self) -> bool { (self.flags & FLAG_IS_AIR) != 0 }",
        "    #[inline] pub const fn propagates_skylight_down(self) -> bool { (self.flags & FLAG_PROPAGATES_SKYLIGHT_DOWN) != 0 }",
        "    #[inline] pub const fn can_occlude(self) -> bool { (self.flags & FLAG_CAN_OCCLUDE) != 0 }",
        "    #[inline] pub const fn is_solid(self) -> bool { (self.flags & FLAG_IS_SOLID) != 0 }",
        "    #[inline] pub const fn can_be_replaced(self) -> bool { (self.flags & FLAG_CAN_BE_REPLACED) != 0 }",
        "    #[inline] pub const fn has_fluid(self) -> bool { (self.flags & FLAG_HAS_FLUID) != 0 }",
        "    #[inline] pub const fn is_fluid_source(self) -> bool { (self.flags & FLAG_IS_FLUID_SOURCE) != 0 }",
        "    #[inline] pub const fn is_motion_blocking(self) -> bool { (self.flags & FLAG_MOTION_BLOCKING) != 0 }",
        "    #[inline] pub const fn is_motion_blocking_no_leaves(self) -> bool { (self.flags & FLAG_MOTION_BLOCKING_NO_LEAVES) != 0 }",
        "}",
        "",
        f"pub static BLOCK_STATE_PROPS: [BlockStateProps; {len(states)}] = [",
    ]
    for emit, ld, flags, speed, item_id in states:
        lines.append(
            f"    BlockStateProps {{ light_emission: {emit}, light_dampening: {ld}, flags: {flags}, item_id: {item_id}, destroy_speed: {fmt_f32(speed)} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append(f"pub static BLOCK_STATE_NBT_PROPS: [&str; {len(state_prop_strings)}] = [")
    for s in state_prop_strings:
        lines.append(f"    {json.dumps(s)},")
    lines.append("];")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {out.name}: {len(states)} block states")


def gen_items(runtime_tables: dict) -> None:
    items = runtime_tables["items"]
    out = RUST_GEN_DIR / "items.rs"
    by_name = sorted(((name, iid) for iid, name, _, _ in items), key=lambda x: x[0])

    lines = [
        "// @generated by scripts/gen_rust_tables.py from live Minecraft 26.3 BuiltInRegistries.ITEM.",
        "// Do not edit manually.",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct ItemInfo {",
        "    pub id: u16,",
        "    pub name: &'static str,",
        "    pub max_stack_size: u8,",
        "    /// Default `BlockStateId` placed by this item if it is a `BlockItem`, else `u32::MAX`.",
        "    pub places_block_state: u32,",
        "}",
        "",
        "impl ItemInfo {",
        "    #[inline]",
        "    pub const fn placed_block_state(self) -> Option<u32> {",
        "        if self.places_block_state == u32::MAX { None } else { Some(self.places_block_state) }",
        "    }",
        "}",
        "",
        f"pub static ITEMS: [ItemInfo; {len(items)}] = [",
    ]
    for iid, name, max_stack, places_state in items:
        ps = "u32::MAX" if places_state < 0 else str(places_state)
        lines.append(
            f"    ItemInfo {{ id: {iid}, name: {json.dumps(name)}, max_stack_size: {max_stack}, places_block_state: {ps} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append(f"pub static ITEM_BY_NAME: [(&str, u16); {len(by_name)}] = [")
    for name, iid in by_name:
        lines.append(f"    ({json.dumps(name)}, {iid}),")
    lines.append("];")
    lines.append("")
    lines.extend([
        "#[inline]",
        "pub fn item_by_id(id: u16) -> Option<&'static ItemInfo> {",
        "    ITEMS.get(id as usize)",
        "}",
        "",
        "#[inline]",
        "pub fn item_by_name(name: &str) -> Option<&'static ItemInfo> {",
        "    ITEM_BY_NAME",
        "        .binary_search_by_key(&name, |(n, _)| *n)",
        "        .ok()",
        "        .map(|i| &ITEMS[ITEM_BY_NAME[i].1 as usize])",
        "}",
        "",
    ])
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {out.name}: {len(items)} items")


def gen_noises() -> None:
    noise_dir = DATA_MC_DIR / "worldgen" / "noise"
    noise_entries = sorted(
        (
            f"minecraft:{nf.relative_to(noise_dir).with_suffix('').as_posix()}",
            nf,
        )
        for nf in noise_dir.rglob("*.json")
    )
    out = RUST_GEN_DIR / "noises.rs"
    lines = [
        "// @generated by scripts/gen_rust_tables.py from data/minecraft/worldgen/noise/**/*.json.",
        "// Do not edit manually.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum NoiseNormalization {",
        "    Disabled,",
        "    Enabled,",
        "    Legacy,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct NormalNoiseSpec {",
        "    pub id: &'static str,",
        "    pub base_octave: i32,",
        "    pub octave_count: usize,",
        "    pub base_amplitude: f64,",
        "    pub normalization: NoiseNormalization,",
        "    pub amplitude_modifiers: &'static [f64],",
        "}",
        "",
        f"pub static VANILLA_NOISES: [NormalNoiseSpec; {len(noise_entries)}] = [",
    ]
    for nid, nf in noise_entries:
        data = json.loads(nf.read_text(encoding="utf-8"))
        base_octave = int(data["base_octave"])
        octave_count = int(data.get("octave_count", 1))
        base_amp = float(data.get("base_amplitude", 1.0))
        norm_raw = data.get("normalize", True)
        if norm_raw is True:
            norm_str = "NoiseNormalization::Enabled"
        elif norm_raw is False:
            norm_str = "NoiseNormalization::Disabled"
        elif norm_raw == "legacy":
            norm_str = "NoiseNormalization::Legacy"
        else:
            raise ValueError(f"Unexpected normalize={norm_raw!r} in {nf}")
        mods = [float(x) for x in data.get("amplitude_modifiers", [])]
        mods_str = ", ".join(fmt_f64(m) for m in mods)
        lines.append(
            f"    NormalNoiseSpec {{ id: {json.dumps(nid)}, base_octave: {base_octave}, octave_count: {octave_count}, base_amplitude: {fmt_f64(base_amp)}, normalization: {norm_str}, amplitude_modifiers: &[{mods_str}] }},"
        )
    lines.append("];")
    lines.append("")
    lines.extend([
        "pub fn vanilla_noise_spec(id: &str) -> Option<&'static NormalNoiseSpec> {",
        "    VANILLA_NOISES",
        "        .binary_search_by_key(&id, |s| s.id)",
        "        .ok()",
        "        .map(|i| &VANILLA_NOISES[i])",
        "}",
        "",
    ])
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {out.name}: {len(noise_entries)} noises")


def quantize_coord(val: float) -> int:
    # Exact match for Java `Climate.quantizeCoord(float)`: `(long)((float)val * 10000.0F)`
    import struct
    f32_val = struct.unpack("<f", struct.pack("<f", val))[0]
    prod = struct.unpack("<f", struct.pack("<f", f32_val * 10000.0))[0]
    return int(prod)


def parse_param_span(raw) -> tuple[int, int]:
    if isinstance(raw, list):
        return (quantize_coord(raw[0]), quantize_coord(raw[1]))
    q = quantize_coord(raw)
    return (q, q)


def gen_overworld_biomes() -> None:
    ow_path = REPORTS_DIR / "biome_parameters" / "minecraft" / "overworld.json"
    data = json.loads(ow_path.read_text(encoding="utf-8"))
    entries = data["biomes"]

    biome_names = sorted({e["biome"] for e in entries})
    biome_idx = {name: i for i, name in enumerate(biome_names)}

    out = RUST_GEN_DIR / "overworld_biomes.rs"
    lines = [
        "// @generated by scripts/gen_rust_tables.py from generated/reports/biome_parameters/minecraft/overworld.json.",
        "// Do not edit manually.",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct ClimateEntry {",
        "    /// `[min, max]` for 7 dimensions: temp, humidity, continentalness, erosion, depth, weirdness, offset.",
        "    pub params: [(i64, i64); 7],",
        "    pub biome_idx: u16,",
        "}",
        "",
        f"pub static OVERWORLD_BIOME_NAMES: [&str; {len(biome_names)}] = [",
    ]
    for name in biome_names:
        lines.append(f"    {json.dumps(name)},")
    lines.append("];")
    lines.append("")
    lines.append(f"pub static OVERWORLD_CLIMATE_ENTRIES: [ClimateEntry; {len(entries)}] = [")
    for e in entries:
        p = e["parameters"]
        t = parse_param_span(p["temperature"])
        h = parse_param_span(p["humidity"])
        c = parse_param_span(p["continentalness"])
        er = parse_param_span(p["erosion"])
        d = parse_param_span(p["depth"])
        w = parse_param_span(p["weirdness"])
        o = quantize_coord(p["offset"])
        bi = biome_idx[e["biome"]]
        lines.append(
            f"    ClimateEntry {{ params: [({t[0]}, {t[1]}), ({h[0]}, {h[1]}), ({c[0]}, {c[1]}), ({er[0]}, {er[1]}), ({d[0]}, {d[1]}), ({w[0]}, {w[1]}), ({o}, {o})], biome_idx: {bi} }},"
        )
    lines.append("];")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {out.name}: {len(entries)} climate entries across {len(biome_names)} unique biomes")


def main() -> None:
    RUST_GEN_DIR.mkdir(parents=True, exist_ok=True)
    runtime_path = REPORTS_DIR / "runtime_tables.json"
    print("Querying Java 26.3 OracleMain for live block/item runtime tables...")
    res = call_oracle([{"op": "dump_runtime_tables", "output": str(runtime_path)}])[0]
    print(f"Oracle exported {res['block_state_count']} block states and {res['item_count']} items.")

    runtime_tables = json.loads(runtime_path.read_text(encoding="utf-8"))
    gen_block_props(runtime_tables)
    gen_items(runtime_tables)
    gen_noises()
    gen_overworld_biomes()

    mod_rs = RUST_GEN_DIR / "mod.rs"
    mod_rs.write_text(
        "// @generated by scripts/gen_rust_tables.py\n"
        "pub mod block_props;\n"
        "pub mod items;\n"
        "pub mod noises;\n"
        "pub mod overworld_biomes;\n",
        encoding="utf-8",
    )
    print("All Rust tables generated successfully.")


if __name__ == "__main__":
    main()
